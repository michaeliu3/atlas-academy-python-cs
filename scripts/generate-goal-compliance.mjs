import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(siteRoot, "content", "course", "goal-compliance.v1.json");
const source = JSON.parse(await readFile(sourcePath, "utf8"));
const outputPath = resolve(siteRoot, source.outputPath);
const checkOnly = process.argv.includes("--check");
const allowedStates = new Set(["complete", "partial", "open", "unverified"]);
const tick = String.fromCharCode(96);

function oneLine(value) {
  return String(value)
    .replace(/\r?\n/gu, " ")
    .replace(/\|/gu, "\\|")
    .trim();
}

function requireText(value, label) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(label + " must be a non-empty string.");
  }
}

function validateSource() {
  if (source.schemaVersion !== 1) {
    throw new Error("goal-compliance source schemaVersion must be 1.");
  }
  requireText(source.asOf, "goal-compliance asOf");
  requireText(source.outputPath, "goal-compliance outputPath");
  if (!Array.isArray(source.requirements) || source.requirements.length === 0) {
    throw new Error("goal-compliance requirements must be a non-empty array.");
  }
  const ids = new Set();
  for (const [index, requirement] of source.requirements.entries()) {
    const label = "requirement " + (index + 1);
    for (const field of ["id", "requirement", "state", "evidence", "openItem"]) {
      requireText(requirement[field], label + "." + field);
    }
    if (!allowedStates.has(requirement.state)) {
      throw new Error(
        label + ".state must be one word: " + [...allowedStates].join(", ") + ".",
      );
    }
    if (ids.has(requirement.id)) {
      throw new Error("Duplicate goal-compliance requirement id: " + requirement.id + ".");
    }
    ids.add(requirement.id);
  }
  for (const field of ["lastFullGate", "currentDraftContent", "lastFullGateApparatus", "lastFullGateBrowser", "reviewReadyRef", "latestSuccessorCheck"]) {
    if (!source.truth?.[field] || typeof source.truth[field] !== "object") {
      throw new Error("goal-compliance truth." + field + " is required.");
    }
  }
}

function checkSummary(check) {
  if (check.state === "not-run") return "not run";
  const pass = check.pass ?? "unknown";
  const fail = check.fail ?? "unknown";
  return String(pass) + " pass / " + String(fail) + " fail";
}

function render() {
  const truth = source.truth;
  const gate = truth.lastFullGate;
  const draft = truth.currentDraftContent;
  const reviewReady = truth.reviewReadyRef;
  const successor = truth.latestSuccessorCheck;
  const axe = truth.openAxeViolations;
  const dependencies = truth.openDependencyAlerts;
  const rows = source.requirements
    .map(function renderRow({ requirement, state, evidence, openItem }) {
      return (
        "| " +
        oneLine(requirement) +
        " | " +
        state +
        " | " +
        oneLine(evidence) +
        " | " +
        oneLine(openItem) +
        " |"
      );
    })
    .join("\n");

  const lines = [
    "# Atlas goal-compliance matrix",
    "",
    "<!-- GENERATED by scripts/generate-goal-compliance.mjs from content/course/goal-compliance.v1.json. Do not edit this file by hand. -->",
    "",
    "> **Generated current truth — " + oneLine(source.asOf) + "**",
    ">",
    "> - Last successful full gate: " +
      tick +
      oneLine(gate.commit) +
      tick +
      " on " +
      oneLine(gate.date) +
      " ([Course CI run " +
      oneLine(gate.runId) +
      "](" +
      gate.url +
      ")); the current review-ready ref is recorded separately below; the separate Draft snapshot is historical evidence only.",
    "> - Current review-ready ref: " +
      tick +
      oneLine(reviewReady.commit) +
      tick +
      " ([PR #" +
      oneLine(reviewReady.prNumber) +
      "](" +
      reviewReady.url +
      ")); required checks are **" +
      oneLine(reviewReady.checkState) +
      "** in Course CI run " +
      tick +
      oneLine(reviewReady.runId) +
      tick +
      " (" +
      oneLine(reviewReady.note) +
      ").",
    "> - Latest PR successor check: `" +
      oneLine(successor.commit) +
      "` ([run " +
      oneLine(successor.runId) +
      "](" +
      successor.url +
      ")) is **" +
      oneLine(successor.checkState) +
      "** (" +
      oneLine(successor.note) +
      ").",
    "> - Latest recorded content-bearing Draft check: " +
      tick +
      oneLine(draft.commit) +
      tick +
      ", " +
      checkSummary(draft) +
      " ([run " +
      oneLine(draft.runId) +
      "](" +
      draft.url +
      ")).",
    "> - Latest recorded full-gate apparatus check: **" +
      checkSummary(truth.lastFullGateApparatus) +
      "**; latest recorded full-gate browser/axe check: **" +
      checkSummary(truth.lastFullGateBrowser) +
      "**.",
    "> - Open red tests: **" +
      oneLine(truth.openRedTests.count) +
      "**. Open axe violations: **" +
      oneLine(axe.count ?? "unknown") +
      "** (latest recorded full-gate result: " +
      oneLine(axe.state) +
      ").",
    "> - Open Dependabot alerts on " +
      tick +
      oneLine(dependencies.branch) +
      tick +
      ": **" +
      oneLine(dependencies.count) +
      "** as of " +
      oneLine(dependencies.asOf) +
      "; see [the dependency risk register](DEPENDENCY_RISK_REGISTER.md).",
    ">",
    "> This is a generated checkability surface, not a degree, credit, certification,",
    "> university-equivalence, mastery, release, or deployment claim. A one-word",
    "> state describes the current evidence boundary; the open-item column prevents",
    "> a passing structural check from being mistaken for learner or release evidence.",
    "",
    "| Requirement | State | Evidence path | One open item |",
    "| --- | --- | --- | --- |",
    rows,
    "",
    "The append-only [historical matrix](GOAL_COMPLIANCE_HISTORY.md) preserves the",
    "older detailed release-hardening record. Update the JSON source and regenerate",
    "this file whenever a requirement's evidence changes; do not edit generated prose.",
    "",
  ];
  return lines.join("\n");
}

validateSource();
const expected = render();
const current = await readFile(outputPath, "utf8").catch(function missingOutput() {
  return null;
});

if (checkOnly) {
  if (current !== expected) {
    throw new Error(
      "Generated goal-compliance matrix is stale. Run pnpm generate:goal-compliance and review the result.",
    );
  }
  console.log("Generated goal-compliance matrix matches its checked-in source.");
} else {
  await writeFile(outputPath, expected, "utf8");
  console.log("Generated " + source.outputPath + " from " + sourcePath + ".");
}
